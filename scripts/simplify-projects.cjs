const up = db.prepare('update projects set summary=?, sections=?, updated_at=unixepoch() where profile_id=? and slug=?')
for (const [slug, plan] of Object.entries(PLANS)) {
  const before = db.prepare('select sections from projects where profile_id=? and slug=?').get(profile.id, slug)
  if (!before) throw new Error(`프로젝트 없음: ${slug}`)
  const b = JSON.parse(before.sections || '[]')
  const bMedia = b.reduce((n, s) => n + (s.media?.length ?? 0), 0)
  const aMedia = plan.sections.reduce((n, s) => n + (s.media?.length ?? 0), 0)
  up.run(plan.summary, JSON.stringify(plan.sections), profile.id, slug)
  console.log(`[${slug}] 섹션 ${b.length} → ${plan.sections.length} · 미디어 ${bMedia} → ${aMedia}`)
}

