const Database = require('better-sqlite3')

const db = new Database(process.env.DATABASE_PATH || './data/hub.db')
const profile = db.prepare("select id from profiles where username='geonho'").get()
if (!profile) throw new Error('프로필 없음')

const img = (id, caption) => ({ kind: 'image', mediaId: id, caption })
const vid = (id, caption, poster) => ({ kind: 'video', mediaId: id, caption, poster })

// 기존 섹션에서 영상 포스터 URL을 그대로 물려받는다(미디어 id → poster).
const posterByMediaId = new Map()
for (const row of db.prepare('select sections from projects where profile_id=?').all(profile.id)) {
  for (const sec of JSON.parse(row.sections || '[]')) {
    for (const m of sec.media || []) if (m.kind === 'video' && m.poster) posterByMediaId.set(m.mediaId, m.poster)
  }
}
const V = (id, caption) => vid(id, caption, posterByMediaId.get(id))

