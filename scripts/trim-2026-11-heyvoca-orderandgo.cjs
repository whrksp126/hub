const Database = require('better-sqlite3')
const db = new Database(process.env.DATABASE_PATH || './data/hub.db')
const load = (slug) => ({ slug, S: JSON.parse(db.prepare('select sections from projects where slug=?').get(slug).sections) })
const by = (S, h) => S.find((s) => (s.heading || '').includes(h))
const save = (slug, summary, S) =>
  db.prepare("update projects set summary=?, metrics='[]', sections=?, updated_at=? where slug=?").run(summary, JSON.stringify(S), Math.floor(Date.now() / 1000), slug)

